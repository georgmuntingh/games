export function parseLevel(text) {
  const rows = text.split('\n').map((row) => row.replace(/\s+$/, ''));
  const height = rows.length;
  const width = Math.max(...rows.map((row) => row.length));
  const walls = new Set();
  const goals = new Set();
  const boxes = new Set();
  let player = null;

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < rows[y].length; x++) {
      const ch = rows[y][x];
      const k = `${x},${y}`;
      if (ch === '#') walls.add(k);
      if (ch === '.' || ch === '*' || ch === '+') goals.add(k);
      if (ch === '$' || ch === '*') boxes.add(k);
      if (ch === '@' || ch === '+') player = { x, y };
    }
  }

  // Interior floor: cells reachable from the player, plus box/goal cells
  // (some levels decorate sealed chambers with boxes already on goals).
  const floor = player ? reachableCells(player, walls, width, height) : new Set();
  for (const k of goals) floor.add(k);
  for (const k of boxes) floor.add(k);

  return { width, height, walls, goals, boxes, player, floor };
}

export function reachableCells(from, walls, width, height) {
  const reached = new Set();
  const stack = [[from.x, from.y]];
  while (stack.length) {
    const [x, y] = stack.pop();
    const k = `${x},${y}`;
    if (x < 0 || y < 0 || x >= width || y >= height) continue;
    if (reached.has(k) || walls.has(k)) continue;
    reached.add(k);
    stack.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
  }
  return reached;
}

export const LEVELS = RAW.split(/\n[ \t]*\n/).map(parseLevel);

export function validateLevels(levels) {
  if (levels.length !== 155) {
    throw new Error(`Expected 155 Microban levels, found ${levels.length}`);
  }
  levels.forEach((level, i) => {
    const n = i + 1;
    if (!level.player) throw new Error(`Level ${n}: no player`);
    if (level.boxes.size === 0) throw new Error(`Level ${n}: no boxes`);
    if (level.boxes.size !== level.goals.size) {
      throw new Error(
        `Level ${n}: ${level.boxes.size} boxes vs ${level.goals.size} goals`
      );
    }
    const reach = reachableCells(
      level.player,
      level.walls,
      level.width,
      level.height
    );
    for (const k of level.boxes) {
      if (!reach.has(k) && !level.goals.has(k)) {
        throw new Error(`Level ${n}: unreachable box not on a goal`);
      }
    }
    for (const k of level.goals) {
      if (!reach.has(k) && !level.boxes.has(k)) {
        throw new Error(`Level ${n}: unreachable goal without a box`);
      }
    }
  });
}
